# Windows Task Scheduler Setup for Auto-Publishing
# This script creates a scheduled task to auto-publish articles every hour

Write-Host "🚀 Setting up Auto-Publishing Cron Job..." -ForegroundColor Cyan
Write-Host ""

# Configuration
$TaskName = "Afrigenomix-AutoPublish"
$ScriptPath = Join-Path $PSScriptRoot "run-autopublish.ps1"
$LogPath = Join-Path $PSScriptRoot "logs"

# Create logs directory if it doesn't exist
if (-not (Test-Path $LogPath)) {
    New-Item -ItemType Directory -Path $LogPath | Out-Null
    Write-Host "✅ Created logs directory: $LogPath" -ForegroundColor Green
}

# Check if task already exists
$ExistingTask = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue

if ($ExistingTask) {
    Write-Host "⚠️  Task '$TaskName' already exists!" -ForegroundColor Yellow
    $response = Read-Host "Do you want to recreate it? (y/n)"
    
    if ($response -eq 'y' -or $response -eq 'Y') {
        Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
        Write-Host "✅ Removed existing task" -ForegroundColor Green
    } else {
        Write-Host "❌ Cancelled" -ForegroundColor Red
        exit
    }
}

# Create the PowerShell script that will run
$RunScript = @"
# Auto-Publish Scheduled Articles
# Generated by setup-cron-windows.ps1

`$LogFile = Join-Path "$LogPath" "autopublish-`$(Get-Date -Format 'yyyy-MM-dd').log"

function Write-Log {
    param([string]`$Message)
    `$timestamp = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
    "`$timestamp - `$Message" | Out-File -Append `$LogFile
    Write-Host `$Message
}

Write-Log "======================================"
Write-Log "Starting auto-publish job..."

try {
    # Get admin token from .env
    `$envPath = Join-Path "$PSScriptRoot" ".env"
    
    if (-not (Test-Path `$envPath)) {
        Write-Log "ERROR: .env file not found"
        exit 1
    }

    # Read JWT_SECRET from .env
    `$jwtSecret = (Get-Content `$envPath | Where-Object { `$_ -match '^JWT_SECRET=' }) -replace 'JWT_SECRET=', '' -replace '"', ''
    
    if (-not `$jwtSecret) {
        Write-Log "ERROR: JWT_SECRET not found in .env"
        exit 1
    }

    # Call the auto-publish endpoint
    `$url = "http://localhost:3000/api/ai/schedule-publish"
    
    Write-Log "Calling: `$url"
    
    `$response = Invoke-RestMethod -Uri `$url -Method Get -Headers @{
        "Authorization" = "Bearer ADMIN_TOKEN_HERE"
    } -ContentType "application/json"
    
    if (`$response.success) {
        Write-Log "✅ SUCCESS: `$(`$response.message)"
        if (`$response.data.published -gt 0) {
            Write-Log "   Published `$(`$response.data.published) article(s)"
        }
        if (`$response.data.facebookPosts) {
            Write-Log "   Posted to Facebook: `$(`$response.data.facebookPosts.Count) post(s)"
        }
    } else {
        Write-Log "❌ ERROR: `$(`$response.error)"
    }
    
} catch {
    Write-Log "❌ EXCEPTION: `$(`$_.Exception.Message)"
    exit 1
}

Write-Log "Auto-publish job completed"
Write-Log "======================================"
"@

# Save the run script
$RunScript | Out-File -FilePath $ScriptPath -Encoding UTF8
Write-Host "✅ Created run script: $ScriptPath" -ForegroundColor Green

# Create the scheduled task
$Action = New-ScheduledTaskAction -Execute "PowerShell.exe" -Argument "-NoProfile -ExecutionPolicy Bypass -File `"$ScriptPath`""

# Run every hour, every day
$Trigger = New-ScheduledTaskTrigger -Once -At (Get-Date) -RepetitionInterval (New-TimeSpan -Hours 1) -RepetitionDuration ([TimeSpan]::MaxValue)

# Settings
$Settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -RunOnlyIfNetworkAvailable

# Register the task
Register-ScheduledTask -TaskName $TaskName -Action $Action -Trigger $Trigger -Settings $Settings -Description "Auto-publish scheduled Afrigenomix blog articles" | Out-Null

Write-Host ""
Write-Host "✅ Scheduled task created successfully!" -ForegroundColor Green
Write-Host ""
Write-Host "📋 Task Details:" -ForegroundColor Cyan
Write-Host "   Name: $TaskName"
Write-Host "   Schedule: Every hour"
Write-Host "   Script: $ScriptPath"
Write-Host "   Logs: $LogPath"
Write-Host ""
Write-Host "🔧 Manage your task:" -ForegroundColor Cyan
Write-Host "   View: Get-ScheduledTask -TaskName '$TaskName'"
Write-Host "   Run now: Start-ScheduledTask -TaskName '$TaskName'"
Write-Host "   Stop: Stop-ScheduledTask -TaskName '$TaskName'"
Write-Host "   Remove: Unregister-ScheduledTask -TaskName '$TaskName'"
Write-Host ""
Write-Host "📊 View logs:" -ForegroundColor Cyan
Write-Host "   Get-Content '$LogPath\autopublish-$(Get-Date -Format 'yyyy-MM-dd').log' -Tail 20"
Write-Host ""
Write-Host "⚠️  IMPORTANT: Make sure your dev server is running!" -ForegroundColor Yellow
Write-Host "   Run: npm run dev" -ForegroundColor Yellow
Write-Host ""
